"""Builds src/medtrum_html.h from tools/medtrum_panel.html (the Medtrum
patch's control panel, in the pod panel's style).
The patch's panel is now folded into the one pump page (src/pump_html.h, built
by tools/gen_pump_panel.py from this same source), and /medtrum serves that
page, so nothing serves this standalone header any more. It is kept -- and
generated -- so the panel source keeps its own generator and the two do not
drift. This only rewrites the API paths."""
import os, sys
here = os.path.dirname(os.path.abspath(__file__))
html = open(os.path.join(here, "medtrum_panel.html")).read()
reps = [
    ("fetch('/command'", "fetch('/medtrum/command'"),
    ("fetch('/status')", "fetch('/medtrum/status')"),
]
for a, b in reps:
    assert html.count(a) == 1, a
    html = html.replace(a, b)
assert ')MEDTRUMHTML"' not in html
with open(os.path.join(here, "..", "src", "medtrum_html.h"), "w") as f:
    f.write("#pragma once\n// Generated by tools/gen_medtrum_panel.py from tools/medtrum_panel.html.\n"
            "// Folded into the pump page (src/pump_html.h) by tools/gen_pump_panel.py;\n"
            "// kept so the panel source keeps its own generator. Nothing serves it.\n"
            "// SPDX-License-Identifier: GPL-3.0-or-later\n"
            'static const char medtrumHTML[] PROGMEM = R"MEDTRUMHTML(' + html + ')MEDTRUMHTML";\n')
