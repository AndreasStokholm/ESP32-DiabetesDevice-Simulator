"""Builds src/pod_html.h from ESP-Sim's control panel (tools/pod_panel.html,
main/panel.html in nightscout/ESP-Sim, with a one-button pod type switch).
The pod's panel is now folded into the one pump page (src/pump_html.h, built by
tools/gen_pump_panel.py from this same source), and /pod serves that page, so
nothing serves this standalone header any more. It is kept -- and generated --
so the panel source keeps its own generator and the two do not drift. This only
rewrites the API paths."""
import os, sys
here = os.path.dirname(os.path.abspath(__file__))
html = open(os.path.join(here, "pod_panel.html")).read()
reps = [
    ("fetch('/command'", "fetch('/pod/command'"),
    ("fetch('/status')", "fetch('/pod/status')"),
]
for a, b in reps:
    assert html.count(a) == 1, a
    html = html.replace(a, b)
assert ')PODHTML"' not in html
with open(os.path.join(here, "..", "src", "pod_html.h"), "w") as f:
    f.write("#pragma once\n// Generated by tools/gen_pod_panel.py from ESP-Sim's panel.html.\n"
            "// Folded into the pump page (src/pump_html.h) by tools/gen_pump_panel.py;\n"
            "// kept so the panel source keeps its own generator. Nothing serves it.\n"
            "// SPDX-License-Identifier: GPL-3.0-or-later\n"
            'static const char podHTML[] PROGMEM = R"PODHTML(' + html + ')PODHTML";\n')
