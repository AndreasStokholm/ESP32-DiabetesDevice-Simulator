"""Builds src/pump_html.h from tools/pump_panel.html plus the pod and Medtrum
panel bodies (tools/pod_panel.html, tools/medtrum_panel.html).

The pump page is one page: a "Simulate" box at the top, and below it only the
panel for the selected pump. The two panels are reused verbatim -- their header,
their main sections and their script -- rather than rewritten. Because both
panels share element ids (resIn, faultIn, failMsg, ...), each panel's ids are
prefixed (p/m) in both its markup and its script, and each script is wrapped in
an IIFE so its top-level names ($, show, refresh, ...) cannot collide. The pod
script's API paths are pointed at /pod and the Medtrum script's at /medtrum;
/fail is shared and left alone.

    python3 tools/gen_pump_panel.py
"""
import os, re

here = os.path.dirname(os.path.abspath(__file__))


def read(name):
    with open(os.path.join(here, name)) as f:
        return f.read()


def extract(html, tag):
    m = re.search(r"<%s>(.*)</%s>" % (tag, tag), html, re.S)
    assert m, "no <%s> in the source" % tag
    return m.group(1)


def ids(html):
    return sorted(set(re.findall(r'id="([^"]+)"', html)))


def prefix_html(html, names, pfx):
    for i in names:
        html = html.replace('id="%s"' % i, 'id="%s%s"' % (pfx, i))
        html = html.replace('for="%s"' % i, 'for="%s%s"' % (pfx, i))
        html = html.replace('aria-labelledby="%s"' % i, 'aria-labelledby="%s%s"' % (pfx, i))
    return html


def prefix_js(js, names, pfx):
    for i in names:
        js = js.replace("$('%s')" % i, "$('%s%s')" % (pfx, i))
        js = js.replace("querySelectorAll('#%s" % i, "querySelectorAll('#%s%s" % (pfx, i))
        js = js.replace("querySelector('#%s" % i, "querySelector('#%s%s" % (pfx, i))
    return js


def panel(src_name, pfx, api):
    """The reused panel: its header + main, ids prefixed, and its script."""
    src = read(src_name)
    head_src = re.search(r"<header>.*?</header>", src, re.S).group(0)
    body_src = extract(src, "main")
    names = ids(head_src + body_src)
    head = prefix_html(head_src, names, pfx)
    body = prefix_html(body_src, names, pfx)
    script = prefix_js(extract(src, "script"), names, pfx)
    for a, b in [("fetch('/command'", "fetch('%s/command'" % api),
                  ("fetch('/status')", "fetch('%s/status')" % api)]:
        assert script.count(a) == 1, (src_name, a)
        script = script.replace(a, b)
    return head + "\n" + body, "(function(){\n" + script + "\n})();"


pod_panel, pod_script = panel("pod_panel.html", "p", "/pod")
medtrum_panel, medtrum_script = panel("medtrum_panel.html", "m", "/medtrum")

html = read("pump_panel.html")
reps = [
    ("<!--POD_PANEL-->", pod_panel),
    ("<!--MEDTRUM_PANEL-->", medtrum_panel),
    ("<!--POD_SCRIPT-->", "<script>\n" + pod_script + "\n</script>"),
    ("<!--MEDTRUM_SCRIPT-->", "<script>\n" + medtrum_script + "\n</script>"),
]
for a, b in reps:
    assert html.count(a) == 1, a
    html = html.replace(a, b)
assert ')PUMPHTML"' not in html
with open(os.path.join(here, "..", "src", "pump_html.h"), "w") as f:
    f.write("#pragma once\n// Generated by tools/gen_pump_panel.py from tools/pump_panel.html and the\n"
            "// pod and Medtrum panel sources (tools/pod_panel.html, tools/medtrum_panel.html).\n"
            "// SPDX-License-Identifier: GPL-3.0-or-later\n"
            'static const char pumpHTML[] PROGMEM = R"PUMPHTML(' + html + ')PUMPHTML";\n')
